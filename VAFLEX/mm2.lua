    local function EnsureFlyControllers()
        local humanoid = MovementState.Humanoid
        local root = MovementState.Root
        if not humanoid or not root or not root.Parent then return nil, nil end

        if not MovementState.FlyApplied then
            MovementState.PlatformStandRestore = humanoid.PlatformStand
            MovementState.FlyApplied = true
        end

        if not MovementState.FlyVelocity or not MovementState.FlyVelocity.Parent then
            local bv = Instance.new("BodyVelocity")
            bv.Name = "VAFLEX_FlyVelocity"
            bv.MaxForce = Vector3.new(1e9, 1e9, 1e9)
            bv.P = 50000
            bv.Velocity = Vector3.zero
            bv.Parent = root
            MovementState.FlyVelocity = bv
        end

        if not MovementState.FlyGyro or not MovementState.FlyGyro.Parent then
            local bg = Instance.new("BodyGyro")
            bg.Name = "VAFLEX_FlyGyro"
            bg.MaxTorque = Vector3.new(1e9, 1e9, 1e9)
            bg.P = 1000000000
            bg.D = 0
            bg.CFrame = root.CFrame
            bg.Parent = root
            MovementState.FlyGyro = bg
        end

        return MovementState.FlyVelocity, MovementState.FlyGyro
    end

