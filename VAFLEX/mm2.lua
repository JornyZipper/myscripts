        if root and root.Parent then
            root.AssemblyAngularVelocity = Vector3.zero
        end

        RestoreNoclip()

        MovementState.WalkApplied = false
        MovementState.JumpApplied = false
        MovementState.RotationApplied = false
        MovementState.SpinAngle = 0
    end

