        if not Running or not Config.AirJumpEnabled or Config.FlyEnabled then return end

        local humanoid, root = GetCharacterParts()
        if not humanoid or not root or humanoid.Health <= 0 then return end

        if humanoid.FloorMaterial ~= Enum.Material.Air then
            MovementState.AirJumps = 0
            MovementState.LastGroundedAt = os.clock()
            return
        end

        -- The normal jump from the ground is jump #1. DoubleJump allows exactly one extra jump in air.
        if os.clock() - MovementState.LastGroundedAt < 0.16 then return end
        if Config.DoubleJump and MovementState.AirJumps >= 1 then return end

        MovementState.AirJumps += 1

        local jumpVelocity
        if Config.JumpBoostEnabled then
            jumpVelocity = Config.JumpBoostPower
        elseif humanoid.UseJumpPower then
            jumpVelocity = humanoid.JumpPower
        else
            jumpVelocity = math.sqrt(2 * workspace.Gravity * math.max(0.1, humanoid.JumpHeight))
        end

        local velocity = root.AssemblyLinearVelocity
        root.AssemblyLinearVelocity = Vector3.new(
            velocity.X,
            math.max(velocity.Y, jumpVelocity),
            velocity.Z
        )
        humanoid:ChangeState(Enum.HumanoidStateType.Jumping)
    end)

    Connect(RunService.Heartbeat, function(delta)
        if not Running then return end

        local humanoid, root = GetCharacterParts()
        if not humanoid or not root or humanoid.Health <= 0 then return end

        if humanoid ~= MovementState.Humanoid or root ~= MovementState.Root then
            BindMovementCharacter(LocalPlayer.Character)
            humanoid, root = GetCharacterParts()
            if not humanoid or not root then return end
        end

        local grounded = humanoid.FloorMaterial ~= Enum.Material.Air
        if grounded then
            MovementState.AirJumps = 0
            MovementState.LastGroundedAt = os.clock()
        end

        -- WalkSpeed
        if Config.WalkSpeedEnabled then
            if not MovementState.WalkApplied then
                MovementState.WalkRestore = humanoid.WalkSpeed
                MovementState.WalkApplied = true
            end
            humanoid.WalkSpeed = Config.WalkSpeedValue
        elseif MovementState.WalkApplied then
            humanoid.WalkSpeed = MovementState.WalkRestore
            MovementState.WalkApplied = false
        end

        -- JumpBoost
        if Config.JumpBoostEnabled then
            if not MovementState.JumpApplied then
                MovementState.JumpRestoreUsePower = humanoid.UseJumpPower
                MovementState.JumpRestorePower = humanoid.JumpPower
                MovementState.JumpRestoreHeight = humanoid.JumpHeight
                MovementState.JumpApplied = true
            end
            humanoid.UseJumpPower = true
            humanoid.JumpPower = Config.JumpBoostPower
        elseif MovementState.JumpApplied then
            pcall(function()
                humanoid.UseJumpPower = MovementState.JumpRestoreUsePower
                humanoid.JumpPower = MovementState.JumpRestorePower
                humanoid.JumpHeight = MovementState.JumpRestoreHeight
            end)
            MovementState.JumpApplied = false
        end

        -- Noclip
        if Config.NoclipEnabled then
            local character = LocalPlayer.Character
            if character then
                for _, item in ipairs(character:GetDescendants()) do
                    if item:IsA("BasePart") then
                        if MovementState.NoclipOriginal[item] == nil then
                            MovementState.NoclipOriginal[item] = item.CanCollide
                        end
                        item.CanCollide = false
                    end
                end
            end
        elseif next(MovementState.NoclipOriginal) ~= nil then
            RestoreNoclip()
        end

        local manualRotation = Config.FlyEnabled or Config.SpinEnabled
            or (grounded and Config.StrafeEnabled)
            or ((not grounded) and Config.AirStrafeEnabled)

        if manualRotation then
            if not MovementState.RotationApplied then
                MovementState.AutoRotateRestore = humanoid.AutoRotate
                MovementState.RotationApplied = true
            end
            humanoid.AutoRotate = false
        elseif MovementState.RotationApplied then
            humanoid.AutoRotate = MovementState.AutoRotateRestore
            MovementState.RotationApplied = false
            root.AssemblyAngularVelocity = Vector3.zero
        end

        -- Fly: BodyVelocity + BodyGyro system. W/S follows the camera LookVector exactly.
        -- The gyro is deliberately very stiff so the character turns almost instantly with the camera.
        if Config.FlyEnabled then
            local camera = workspace.CurrentCamera
            local bv, bg = EnsureFlyControllers()

            if camera and bv and bg then
                local dir = Vector3.zero

                if UserInputService.KeyboardEnabled then
                    if UserInputService:IsKeyDown(Enum.KeyCode.W) then
                        dir += camera.CFrame.LookVector
                    end
                    if UserInputService:IsKeyDown(Enum.KeyCode.S) then
                        dir -= camera.CFrame.LookVector
                    end
                    if UserInputService:IsKeyDown(Enum.KeyCode.A) then
                        dir -= camera.CFrame.RightVector
                    end
                    if UserInputService:IsKeyDown(Enum.KeyCode.D) then
                        dir += camera.CFrame.RightVector
                    end
                else
                    -- Mobile: use the thumbstick MoveDirection, remapped into camera space.
                    local move = humanoid.MoveDirection
                    local flatLook = Vector3.new(camera.CFrame.LookVector.X, 0, camera.CFrame.LookVector.Z)
                    local flatRight = Vector3.new(camera.CFrame.RightVector.X, 0, camera.CFrame.RightVector.Z)
                    if flatLook.Magnitude > 0.001 then flatLook = flatLook.Unit end
                    if flatRight.Magnitude > 0.001 then flatRight = flatRight.Unit end
                    local forwardInput = move:Dot(flatLook)
                    local rightInput = move:Dot(flatRight)
                    dir = camera.CFrame.LookVector * forwardInput + camera.CFrame.RightVector * rightInput
                end

                if dir.Magnitude > 1 then
                    dir = dir.Unit
                end

                bv.Velocity = dir * Config.FlySpeed
                bg.CFrame = camera.CFrame
                humanoid.PlatformStand = true
                root.AssemblyAngularVelocity = Vector3.zero
            end
        end

        -- LongJump
        if Config.LongJumpEnabled and not grounded and not Config.FlyEnabled then
            local move = humanoid.MoveDirection
            if move.Magnitude > 0.05 then
                local horizontal = Vector3.new(move.X, 0, move.Z)
                if horizontal.Magnitude > 0 then
                    horizontal = horizontal.Unit
                    local baseSpeed = Config.WalkSpeedEnabled and Config.WalkSpeedValue or humanoid.WalkSpeed
                    local targetSpeed = baseSpeed + Config.LongJumpSpeed
                    local velocity = root.AssemblyLinearVelocity
                    root.AssemblyLinearVelocity = Vector3.new(
                        horizontal.X * targetSpeed,
                        velocity.Y,
                        horizontal.Z * targetSpeed
                    )
                end
            end
        end

        -- Spin has orientation priority but never replaces the movement velocity.
        if Config.SpinEnabled then
            if not MovementState.SpinActive then
                local _, currentYaw, _ = root.CFrame:ToOrientation()
                MovementState.SpinAngle = currentYaw
                MovementState.SpinActive = true
                MovementState.SpinDirection = 1
                MovementState.SpinSwitchTimer = 0
            end

            local direction = 1
            local mode = Config.SpinMode or "Clockwise"

            if mode == "Counter" then
                direction = -1
            elseif mode == "Alternate" then
                MovementState.SpinSwitchTimer += delta
                if MovementState.SpinSwitchTimer >= 0.55 then
                    MovementState.SpinSwitchTimer = 0
                    MovementState.SpinDirection *= -1
                end
                direction = MovementState.SpinDirection
            elseif mode == "Random" then
                MovementState.SpinSwitchTimer += delta
                if MovementState.SpinSwitchTimer >= 0.12 then
                    MovementState.SpinSwitchTimer = 0
                    MovementState.SpinDirection = math.random(0, 1) == 0 and -1 or 1
                end
                direction = MovementState.SpinDirection
            else
                MovementState.SpinDirection = 1
                MovementState.SpinSwitchTimer = 0
            end

            MovementState.SpinAngle = (MovementState.SpinAngle + math.rad(Config.SpinSpeed * 7.2) * direction * delta) % (math.pi * 2)
            root.CFrame = CFrame.new(root.Position) * CFrame.Angles(0, MovementState.SpinAngle, 0)
            root.AssemblyAngularVelocity = Vector3.zero
        elseif not Config.FlyEnabled then
            MovementState.SpinActive = false
            -- Instant ground/air strafing. No waiting for Humanoid.AutoRotate interpolation.
            local strafeActive = (grounded and Config.StrafeEnabled)
                or ((not grounded) and Config.AirStrafeEnabled)

            if strafeActive then
                local move = humanoid.MoveDirection
                local horizontal = Vector3.new(move.X, 0, move.Z)
                if horizontal.Magnitude > 0.05 then
                    horizontal = horizontal.Unit
                    root.CFrame = CFrame.lookAt(root.Position, root.Position + horizontal)
                    root.AssemblyAngularVelocity = Vector3.zero
                end
            end
        end
    end)
end

