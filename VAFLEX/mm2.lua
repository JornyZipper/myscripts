    Main.Visible = false

    task.delay(0.62, function()
        if crashLayer and crashLayer.Parent then
            crashLayer:Destroy()
        end

        if onFinished then
            onFinished()
        end
    end)
end

UIControls.CrashVaflex = function()
    if not Running then return end

    Running = false
    TransitionBusy = true

    if UIControls.RestoreMovement then
        pcall(UIControls.RestoreMovement)
    end

    UIControls.PlayCrashWaterBall(function()
        for _, connection in ipairs(Connections) do
            pcall(function()
                connection:Disconnect()
            end)
        end

        table.clear(Connections)

        local roleKeys = {}
        for player in pairs(RoleESPObjects) do
            table.insert(roleKeys, player)
        end
        for _, player in ipairs(roleKeys) do
            RemoveRoleESP(player)
        end

        local gunKeys = {}
        for object in pairs(GunESPObjects) do
            table.insert(gunKeys, object)
        end
        for _, object in ipairs(gunKeys) do
            RemoveGunESP(object)
        end

        if LoaderGui and LoaderGui.Parent then
            LoaderGui:Destroy()
        end

        if SoundsFolder and SoundsFolder.Parent then
            SoundsFolder:Destroy()
        end

        if UIControls.EmbeddedLogoImage then
            pcall(function()
                UIControls.EmbeddedLogoImage:Destroy()
            end)
            UIControls.EmbeddedLogoImage = nil
            UIControls.EmbeddedLogoContent = nil
        end

        if Gui and Gui.Parent then
            Gui:Destroy()
        end

        pcall(function()
            if script and script.Parent then
                script:Destroy()
            end
        end)
    end)
end

Connect(CrashButton.MouseButton1Click, UIControls.CrashVaflex)

